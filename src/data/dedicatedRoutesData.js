/**
 * Returns list of dedicated routes for an operator name.
 * If the operator has multiple individual routes, returns that list.
 * Includes transliteration fallbacks (Tarakeshwar <-> Tarakeshwor).
 */
export function getOperatorRoutes(operatorName) {
  if (!operatorName) return [];
  if (DEDICATED_ROUTES_MAP[operatorName]) {
    return DEDICATED_ROUTES_MAP[operatorName];
  }
  
  const norm1 = operatorName.replace(/shwar/gi, 'shwor');
  if (DEDICATED_ROUTES_MAP[norm1]) {
    return DEDICATED_ROUTES_MAP[norm1];
  }
  const norm2 = operatorName.replace(/shwor/gi, 'shwar');
  if (DEDICATED_ROUTES_MAP[norm2]) {
    return DEDICATED_ROUTES_MAP[norm2];
  }
  
  const lower = operatorName.toLowerCase().trim();
  for (const [key, routes] of Object.entries(DEDICATED_ROUTES_MAP)) {
    if (key.toLowerCase() === lower || lower.includes(key.toLowerCase()) || key.toLowerCase().includes(lower)) {
      return routes;
    }
  }
  return [];
}
